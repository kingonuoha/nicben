/**
 * Password hashing and verification — `decisions.md` **D-026**.
 *
 * "argon2id via `@node-rs/argon2` — prebuilt binaries for win32 and linux, so no
 * compilation step and no toolchain requirement on the client's machine or on
 * Vercel. **Fallback:** if the package fails to install or load on this platform,
 * use `bcryptjs` at cost ≥ 12 and record the substitution."
 *
 * **Outcome on this platform:** `@node-rs/argon2` installed and loaded on win32
 * without a toolchain and without a build step, so argon2id is the algorithm in
 * use and **no substitution was made**. The hash format this module produces and
 * consumes is `$argon2id$v=19$m=19456,t=2,p=1$…`, which is the OWASP-recommended
 * parameter set (19 MiB, t=2, p=1) rather than the library's defaults merely being
 * inherited — see `ARGON2_OPTIONS` below. It is passed explicitly for that reason:
 * a library default that changed in a future version must not be able to weaken
 * stored credentials silently.
 *
 * ### Why the native module is imported lazily
 *
 * `@node-rs/argon2` is a N-API binary. Importing it at module scope would place it
 * on the module graph of anything that imports this file, including a client
 * component that reached it by accident through a barrel re-export. The loader
 * below is a cached dynamic `import()`, the same discipline
 * `lib/data/adapters/mongo.ts` uses for the `mongodb` driver, which keeps a binary
 * out of every bundle that cannot use it.
 *
 * ### Constant-time discipline
 *
 * `verify()` — argon2's own comparison — is the credential check, and it runs in
 * constant time over the derived key. Two further properties are enforced here
 * because they are the ones a timing oracle actually leaks through:
 *
 * 1. **An unknown account still performs a full argon2 verification.** It is
 *    verified against a dummy hash of the same parameter set, not short-circuited
 *    (`lib/auth/login.ts`). Without that, "no such user" would return in
 *    microseconds and "wrong password" in tens of milliseconds.
 * 2. **A malformed stored hash is not distinguishable either.** A verify that
 *    throws is reported as a failed verification, not as an error, so a
 *    provisioning mistake cannot become a second response shape.
 */

/* -------------------------------------------------------------------------- */
/* argon2id parameters                                                         */
/* -------------------------------------------------------------------------- */

/**
 * 19 MiB, t=2, p=1, 32-byte output, argon2id — the OWASP Password Storage Cheat
 * Sheet's first recommended configuration. Roughly 40–60 ms per verification on
 * the development machine, which is slow enough to make offline guessing expensive
 * and fast enough for an interactive login.
 */
export const ARGON2_OPTIONS = {
  memoryCost: 19_456,
  timeCost: 2,
  parallelism: 1,
  outputLen: 32,
} as const;

/** The `$argon2…` prefixes this module can verify. Anything else is not a hash. */
const ARGON2_PREFIX = "$argon2";

/**
 * The narrow runtime shape this module uses.
 *
 * The package's own `.d.ts` declares `algorithm` as an **ambient const enum**, and
 * `tsconfig.json` enables `isolatedModules`, so reading `Algorithm.Argon2id` in a type
 * position is a compile error ("Cannot access ambient const enums when
 * 'isolatedModules' is enabled"). The value does exist at runtime — it is generated by
 * napi-rs — so the module is reached through this interface instead. The alternative,
 * dropping the explicit algorithm and inheriting the library default, would give up the
 * guarantee that a future default change cannot silently move stored credentials off
 * argon2id.
 */
interface Argon2Runtime {
  hash(password: string, options?: Record<string, unknown>): Promise<string>;
  verify(hashed: string, password: string): Promise<boolean>;
  readonly Algorithm: { readonly Argon2id: number };
}

let argon2Promise: Promise<Argon2Runtime> | null = null;

async function loadArgon2(): Promise<Argon2Runtime> {
  if (!argon2Promise) {
    argon2Promise = import("@node-rs/argon2")
      .then((module) => module as unknown as Argon2Runtime)
      .catch((error: unknown) => {
        // Reset so a transient load failure can be retried rather than being cached
        // as a permanent one.
        argon2Promise = null;
        throw error;
      });
  }
  return argon2Promise;
}

/** True when the value has the shape of a hash this module can verify. */
export function looksLikeArgon2Hash(value: string): boolean {
  return value.startsWith(ARGON2_PREFIX);
}

/* -------------------------------------------------------------------------- */
/* Hashing                                                                     */
/* -------------------------------------------------------------------------- */

/**
 * Hash a password for storage. Used by provisioning only
 * (`web/scripts/hash-admin-password.mjs` and `web/docs/admin-provisioning.md`);
 * **no request path in this application writes a `passwordHash`**.
 *
 * The caller must already have accepted the password against
 * `checkAdminPasswordPolicy` — hashing does not enforce the policy, because a
 * verification path must never reject a stored credential on policy grounds.
 */
export async function hashAdminPassword(password: string): Promise<string> {
  const { hash, Algorithm } = await loadArgon2();
  return hash(password, { ...ARGON2_OPTIONS, algorithm: Algorithm.Argon2id });
}

/* -------------------------------------------------------------------------- */
/* Verification                                                                */
/* -------------------------------------------------------------------------- */

export interface PasswordVerificationResult {
  /** `true` only when the password matches the stored hash. */
  ok: boolean;
  /**
   * A short machine-readable reason. **Never** contains the password, the hash or
   * a library message, so it is safe to put in a log line (`06` §43).
   */
  reason: "match" | "mismatch" | "not-a-hash" | "verifier-unavailable";
}

/**
 * Verify a candidate password against a stored hash.
 *
 * Returns a decision rather than throwing: every failure mode — wrong password,
 * unparseable stored hash, native module unavailable — resolves to `ok: false`
 * with a distinct `reason` for the server log. That is what keeps the caller's
 * response shape identical in all of them (`decisions.md` D-028 fail closed).
 */
export async function verifyAdminPassword(
  storedHash: string,
  candidate: string,
): Promise<PasswordVerificationResult> {
  if (!looksLikeArgon2Hash(storedHash)) {
    return { ok: false, reason: "not-a-hash" };
  }

  try {
    const { verify } = await loadArgon2();
    const ok = await verify(storedHash, candidate);
    return { ok, reason: ok ? "match" : "mismatch" };
  } catch {
    // A malformed hash, or a binary that will not load. Both fail closed, and
    // neither is distinguishable from a wrong password by the caller.
    return { ok: false, reason: "verifier-unavailable" };
  }
}

/* -------------------------------------------------------------------------- */
/* Dummy verification target                                                   */
/* -------------------------------------------------------------------------- */

/**
 * A real argon2id hash of a random value that is discarded immediately. It exists
 * so an unknown account can be verified against *something* with the same
 * parameters, which is what makes the unknown-account and wrong-password paths
 * take comparable time.
 *
 * It can never be a working credential: the value it hashes is never generated
 * again, is never stored, and is not derivable from the hash.
 */
let dummyHashPromise: Promise<string> | null = null;

function dummyHash(): Promise<string> {
  if (!dummyHashPromise) {
    dummyHashPromise = (async () => {
      const { randomBytes } = await import("node:crypto");
      return hashAdminPassword(randomBytes(32).toString("base64url"));
    })().catch((error: unknown) => {
      dummyHashPromise = null;
      throw error;
    });
  }
  return dummyHashPromise;
}

export interface DummyVerificationResult {
  /** Always `false`. The value is the fact that the work happened. */
  ok: false;
  reason: "unknown-account";
}

/**
 * Spend the same argon2 work an unknown account would otherwise skip, then report
 * failure.
 *
 * `lib/auth/login.ts` calls this on the no-such-account path. The result is
 * deliberately a constant: there is nothing to compare.
 */
export async function verifyAgainstDummyHash(candidate: string): Promise<DummyVerificationResult> {
  try {
    const { verify } = await loadArgon2();
    await verify(await dummyHash(), candidate);
  } catch {
    // Even the timing-equalisation step must not be able to throw out of the login
    // pipeline; the outcome is failure either way.
  }
  return { ok: false, reason: "unknown-account" };
}

/* -------------------------------------------------------------------------- */
/* Password policy — D-029                                                     */
/* -------------------------------------------------------------------------- */

/**
 * `docs/06-tech-and-security-spec.md` §29: "Admin 2FA (TOTP) if budget allows;
 * otherwise strong password policy plus rate limit." `decisions.md` **D-029**
 * implements the alternative and records TOTP as deferred.
 *
 * The policy is enforced at **provisioning** time, which is the only time a
 * password exists in plaintext. It is not enforced at login: rejecting a stored
 * credential because it would no longer pass a policy would lock the operator out
 * of their own portal.
 */
export const ADMIN_PASSWORD_POLICY = {
  minLength: 12,
  maxLength: 200,
  /** Non-alphanumeric characters required, so "twelveletters" is not accepted. */
  minSymbols: 1,
  /** Digits required. */
  minDigits: 1,
  /**
   * A short deny list of the passwords that appear in every credential-stuffing
   * dictionary. It is deliberately short and obvious rather than a large list:
   * length plus composition is the control, and a long list of common passwords
   * committed to the repository would itself be a liability.
   */
  denied: [
    "admin",
    "administrator",
    "nicben",
    "nicbenadmin",
    "password",
    "password1234",
    "changeme",
    "letmein",
    "qwertyuiop",
    "123456789012",
  ],
} as const;

export interface PasswordPolicyViolation {
  rule: "min-length" | "max-length" | "min-symbols" | "min-digits" | "denied-value";
  /** Operator-facing description. Never echoes the password. */
  detail: string;
}

/**
 * Assess a candidate password against `ADMIN_PASSWORD_POLICY`.
 *
 * Returns the list of violations; empty means accepted. **Never returns or logs the
 * password**, and never includes it in a `detail` string.
 */
export function checkAdminPasswordPolicy(password: string): PasswordPolicyViolation[] {
  const violations: PasswordPolicyViolation[] = [];
  if (password.length < ADMIN_PASSWORD_POLICY.minLength) {
    violations.push({
      rule: "min-length",
      detail: `must be at least ${ADMIN_PASSWORD_POLICY.minLength} characters`,
    });
  }
  if (password.length > ADMIN_PASSWORD_POLICY.maxLength) {
    violations.push({
      rule: "max-length",
      detail: `must be at most ${ADMIN_PASSWORD_POLICY.maxLength} characters`,
    });
  }
  const symbols = password.replace(/[A-Za-z0-9]/g, "").length;
  if (symbols < ADMIN_PASSWORD_POLICY.minSymbols) {
    violations.push({
      rule: "min-symbols",
      detail: `must contain at least ${ADMIN_PASSWORD_POLICY.minSymbols} non-alphanumeric character`,
    });
  }
  if ((password.match(/[0-9]/g) ?? []).length < ADMIN_PASSWORD_POLICY.minDigits) {
    violations.push({
      rule: "min-digits",
      detail: `must contain at least ${ADMIN_PASSWORD_POLICY.minDigits} digit`,
    });
  }
  const normalised = password.trim().toLowerCase();
  if (ADMIN_PASSWORD_POLICY.denied.some((denied) => normalised === denied)) {
    violations.push({ rule: "denied-value", detail: "is a well-known password" });
  }
  return violations;
}

/** Convenience predicate for a provisioning script's control flow. */
export function isAdminPasswordAcceptable(password: string): boolean {
  return checkAdminPasswordPolicy(password).length === 0;
}
